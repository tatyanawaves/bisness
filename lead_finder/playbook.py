def _offer_lines(slots: dict, terms: dict) -> list[dict]:
    lines = [
        _reply("Если назвали интересные позиции, предложите сравнить цены",
               f"Тогда предлагаю так: я посмотрю по этим {terms['items_dat']} цены и условия, а вы сравните нас с текущими {terms['suppliers_ins']}. Какая {terms['item']} сейчас ближайшая к закупке?"),
    ]
    for idea in slots.get("ideas", []):
        note = "Это предположение из анализа, а не факт, поэтому спрашивайте, а не утверждайте."
        if idea.get("why"):
            note = f"Почему: {idea['why']} {note}"
        lines.append(_reply(f"Предположение из анализа: {idea['product']}", idea["question"], note=note))
    lines.append(_reply("Если готовы попробовать", terms["first_step"], note="Не пытайтесь сразу забрать весь объём."))
    lines.append(_reply("Если спрашивают цену сразу",
                        f"Давайте сначала определим {terms['item_acc']} и объём, тогда я дам вам конкретную цену."))
    return lines


def spoken_lines(content: dict) -> list[str]:
    """Все реплики скрипта: их проверяем на запрещённые обороты."""
    lines = []
    for stage in content["stages"]:
        for line in stage["lines"]:
            if "say" in line:
                lines.append(line["say"])
            lines.extend(line.get("says", []))
    for objection in content["objections"]:
        lines.extend(objection["says"])
    lines.append(content["whatsapp"])
    return lines


def lint(content: dict) -> list[str]:
    """Реплики, которые нарушают правила уроков."""
    return [line for line in spoken_lines(content) if find_forbidden(line)]


def to_plain_text(content: dict) -> str:
    """Скрипт одним текстом: для копирования и хранения в базе."""
    company = content["company"]
    out = [f"Скрипт звонка: {company['name']} ({company['city']})"]
    if company["phones"]:
        out.append("Телефон: " + ", ".join(company["phones"]))
    out.append("")
    for number, stage in enumerate(content["stages"], start=1):
        out.append(f"{number}. {stage['title']}")
        out.append(f"Цель: {stage['goal']}")
        if stage.get("formula"):
            out.append(f"Формула: {stage['formula']}")
        for line in stage["lines"]:
            if "say" in line:
                out.append(f"- {line['say']}")
            else:
                out.append(f"{line['if']}:")
                out.extend(f"  - {say}" for say in line["says"])
            if line.get("note"):
                out.append(f"  ({line['note']})")
        out.append("")
    out.append("Возражения")
    for objection in content["objections"]:
        out.append(f"«{objection['trigger']}»:")
        out.extend(f"  - {say}" for say in objection["says"])
    out += ["", "Сообщение в WhatsApp после звонка", content["whatsapp"], "", "После звонка запишите"]
    out.extend(f"- {item}" for item in content["after_call"])
    out += ["", "Не говорить"]
    out.extend(f"- {item}" for item in content["never_say"])
    return "\n".join(out)
