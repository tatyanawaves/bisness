def find_forbidden(text: str) -> list[str]:
    """Возвращает запрещённые уроками обороты, найденные в тексте."""
    return [p.pattern for p in _FORBIDDEN if p.search(text or "")]


def _capitalize(text: str) -> str:
    return text[:1].upper() + text[1:] if text else text


def _sentences(text: str) -> str:
    """Каждое предложение реплики начинается с большой буквы."""
    return re.sub(r"([.!?]\s+)([а-яё])", lambda m: m.group(1) + m.group(2).upper(), _capitalize(text))


def default_slots(analysis: dict | None, profile: dict) -> dict:
    """Значения по умолчанию: из типа компании. Работают и без модели."""
    data = (analysis or {}).get("data") or {}
    activity = get_activity(data.get("activity_key"))
    forms = {"gen": profile["offer_gen"], "dat": profile["offer_dat"]}
    return {
        "secretary_question": activity["secretary"].format(**forms),
        "buyer_role": data.get("buyer") or activity["buyer"],
        "spec_owner": activity["spec_owner"],
        "approver": "руководитель",
        "process_question": activity["process"].format(**forms),
        "parameter_question": "Какие характеристики обычно берёте?",
        "volume_question": "Какой объём обычно идёт?",
        "critical_question": activity["critical"].format(**forms),
        "ideas": [],
    }


def _normalize_slot(name: str, value: str) -> str:
    """Приводит реплику модели к виду, в котором она встанет в скрипт."""
    value = value.strip().strip('"«»').strip()
    if name != "secretary_question":
        return _sentences(value) if name in QUESTION_SLOTS else value
    # Приветствие и «подскажите» скрипт добавляет сам
    value = re.sub(
        r"^(добрый день[.,!]?\s*)?(подскажите[,]?\s*(пожалуйста[,]?\s*)?)?", "", value, flags=re.IGNORECASE
    )
    return value[:1].lower() + value[1:] if value[1:2].islower() else value


def clean_slots(raw: dict, defaults: dict) -> tuple[dict, list[str]]:
    """
    Проверяет ответ модели. Пустая, слишком длинная или запрещённая реплика
    заменяется значением по умолчанию, поэтому скрипт не выходит за рамки уроков.
    """
    slots = dict(defaults)
    rejected = []
    for name, limit in SLOT_LIMITS.items():
        value = raw.get(name)
        if not isinstance(value, str) or not value.strip():
            continue
        value = _normalize_slot(name, value)
        if not value or len(value) > limit or find_forbidden(value):
            rejected.append(name)
            continue
        if name in QUESTION_SLOTS and not value.endswith("?"):
            rejected.append(name)
            continue
        slots[name] = value

    ideas = []
    for idea in raw.get("ideas") or []:
        if not isinstance(idea, dict):
            continue
        product, why, question = (str(idea.get(k) or "").strip() for k in ("product", "why", "question"))
        if not product or not question or not question.endswith("?") or find_forbidden(question):
            rejected.append("ideas")
            continue
        ideas.append({"product": product[:100], "why": why[:240], "question": _sentences(question)[:240]})
    slots["ideas"] = ideas[:3]
    return slots, rejected


def _say(text: str, note: str = "") -> dict:
    return {"say": text, "note": note}


def _reply(trigger: str, *says: str, note: str = "") -> dict:
    return {"if": trigger, "says": list(says), "note": note}


